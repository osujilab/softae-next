# ── The forward model, and the truth the tests measure against ───────────────

#: One geometry, one interfacial chemistry — the three quantities the design shares.
TRUE_SHARED = {"Qg": 1.2e-9, "ng": 0.92, "nd": 0.76}

#: A conductivity ladder. The values bracket the NIST standards' fitted ``R_sol``.
TRUE_R_SOL = {"dilute_a": 70_000.0, "dilute_b": 38_000.0,
              "mid": 2_400.0, "concentrated": 800.0}

WIDE_BAND = (4.0, 2.0e5)


def synth(
    label: str,
    r_sol: float,
    *,
    band: tuple[float, float] = WIDE_BAND,
    n: int = 40,
    qd: float = 2e-6,
    pinned_l_H: float = 0.0,
    y_shunt: np.ndarray | None = None,
    shared: dict[str, float] | None = None,
) -> ConstrainedSpectrum:
    """A spectrum generated by :func:`model_impedance` itself, with known truth."""
    freq = np.logspace(math.log10(band[0]), math.log10(band[1]), n)
    params = dict(shared or TRUE_SHARED)
    params.update({"R0": 0.15 * r_sol, "R1": 0.85 * r_sol, "Qd": qd})
    ys = np.zeros(n, dtype=complex) if y_shunt is None else np.asarray(y_shunt)
    z = model_impedance(freq, params, ys, pinned_l_H)
    return ConstrainedSpectrum(label=label, freq_hz=freq, z=z, y_shunt=ys,
                               pinned_l_H=pinned_l_H, reference_ohm=r_sol)


@pytest.fixture
def ladder() -> list[ConstrainedSpectrum]:
    return [synth(label, r) for label, r in TRUE_R_SOL.items()]


# ── The split: three shared, three per spectrum, L in neither ────────────────

def test_parameter_split_partitions_names_with_l_pinned_out() -> None:
    assert set(SHARED_PARAMS) | set(PER_SPECTRUM_PARAMS) == set(PARAM_NAMES)
    assert not set(SHARED_PARAMS) & set(PER_SPECTRUM_PARAMS)
    # L is pinned. A pinned quantity in the parameter vector is one bounds edit away
    # from being fitted, which is the defect overhaul F5 recorded.
    assert "L" not in PARAM_NAMES and "L" not in BOUNDS
    # Nor is a leak resistance, which would be degenerate against a supplied shunt.
    assert "Rleak" not in PARAM_NAMES


def test_fit_shared_recovers_the_shared_three_from_the_forward_model(ladder) -> None:
    artifact = fit_shared(ladder)
    for name, truth in TRUE_SHARED.items():
        assert getattr(artifact, name) == pytest.approx(truth, rel=1e-3), name
    assert artifact.labels == tuple(TRUE_R_SOL)
    assert artifact.railed() == ()


def test_fit_shared_shares_one_value_across_every_spectrum(ladder) -> None:
    """The property that distinguishes this from N independent fits."""
    artifact = fit_shared(ladder)
    frozen = artifact.shared
    assert set(frozen) == set(SHARED_PARAMS)
    # Each spectrum's own truth differs in R_sol by ~90x, yet one triple serves all.
    for spec in ladder:
        fit = fit_frozen(spec, artifact)
        assert fit.R_sol == pytest.approx(spec.reference_ohm, rel=1e-3), spec.label


def test_fit_frozen_varies_only_the_per_spectrum_three(ladder) -> None:
    artifact = fit_shared(ladder)
    a = fit_frozen(ladder[0], artifact)
    b = fit_frozen(ladder[-1], artifact)
    # The per-spectrum parameters move with the spectrum...
    assert a.R0 != b.R0 and a.R1 != b.R1
    # ...while the artifact they were fitted against is unchanged by fitting.
    assert artifact.shared == fit_shared(ladder).shared


def test_continuation_reset_names_only_the_resistances() -> None:
    """The seeding rule worth 1.4 % against 28 000 % — see the constant's docstring."""
    assert set(CONTINUATION_RESET) == {"R0", "R1"}
    assert set(CONTINUATION_RESET) <= set(PER_SPECTRUM_PARAMS)


# ── R_sol = R0 + R1, unconditionally ─────────────────────────────────────────

def test_r_sol_is_the_sum_not_the_bulk_term(ladder) -> None:
    artifact = fit_shared(ladder)
    for spec in ladder:
        fit = fit_frozen(spec, artifact)
        assert fit.R_sol == fit.R0 + fit.R1
        # R1 alone is short of the truth by the whole series term, which is the
        # sigma-dependent shortfall the sum exists to avoid.
        assert fit.R1 < spec.reference_ohm * 0.95


def test_r_sol_is_reported_even_when_the_split_is_unidentifiable() -> None:
    """No rho test, no split-vs-sum branch: the sum is always what comes out.

    A spectrum whose series term is a thousandth of the total cannot support the
    split, and this is exactly the case the legacy path declines to report.
    """
    spec = synth("tiny_series", 50_000.0)
    spec = ConstrainedSpectrum(
        label="tiny_series", freq_hz=spec.freq_hz,
        z=model_impedance(spec.freq_hz,
                          {**TRUE_SHARED, "R0": 50.0, "R1": 49_950.0, "Qd": 2e-6},
                          spec.y_shunt, 0.0),
        y_shunt=spec.y_shunt, reference_ohm=50_000.0)
    artifact = fit_shared([spec, *[synth(k, v) for k, v in TRUE_R_SOL.items()]])
    fit = fit_frozen(spec, artifact)
    assert fit.R_sol == pytest.approx(50_000.0, rel=1e-2)


# ── The pinned inductance ────────────────────────────────────────────────────

def test_pinned_inductance_is_consumed_not_fitted() -> None:
    """A spectrum built with a real lead L is recovered when L is pinned to it."""
    l_lead = 1.7294984432805884e-06          # mux16 L_lead_H, ch25
    specs = [synth(k, v, pinned_l_H=l_lead) for k, v in TRUE_R_SOL.items()]
    artifact = fit_shared(specs)
    for name, truth in TRUE_SHARED.items():
        assert getattr(artifact, name) == pytest.approx(truth, rel=1e-3), name
    for spec in specs:
        assert fit_frozen(spec, artifact).R_sol == pytest.approx(
            spec.reference_ohm, rel=1e-3)


def test_wrong_pinned_inductance_moves_the_answer() -> None:
    """The positive control for the test above: pinning L must actually do something.

    Without this, ``test_pinned_inductance_is_consumed_not_fitted`` would pass just as
    happily if ``pinned_l_H`` were ignored entirely — SUBAGENT_RULES §3.1(e).
    """
    l_lead = 5e-4                            # far larger than any real lead
    truth = np.array([model_impedance(np.array([2.0e5]),
                                      {**TRUE_SHARED, "R0": 120.0, "R1": 680.0,
                                       "Qd": 2e-6},
                                      np.zeros(1, dtype=complex), L)[0]
                      for L in (0.0, l_lead)])
    assert abs(truth[1] - truth[0]) > 1.0


