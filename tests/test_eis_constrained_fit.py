# ── G_fixture, consumed point by point ───────────────────────────────────────

def _dielectric_table(n: int = 20) -> FixtureConductance:
    """``G = ωC·tanδ`` — this fixture's measured shape, ``d ln G/d ln f`` ≈ 1."""
    f = np.logspace(math.log10(14.28), math.log10(2.0e5), n)
    g = 2.0 * math.pi * f * 5.3e-11 * 0.05
    return FixtureConductance(freq_hz=tuple(f), G_S=tuple(g), exponent=1.0)


def test_fixture_admittance_is_evaluated_per_frequency_not_collapsed() -> None:
    table = _dielectric_table()
    freq = np.logspace(math.log10(20.0), math.log10(1.0e5), 25)
    shunt = fixture_admittance(freq, table, 0.0)
    assert isinstance(shunt, ShuntTable)
    assert shunt.y.shape == freq.shape
    # A scalar would give one value repeated. This spans three decades, monotonically,
    # because on this fixture the loss is dielectric.
    real = shunt.y.real
    assert np.all(np.diff(real) > 0)
    assert real[-1] / real[0] > 1e3


def test_fixture_admittance_adds_the_stray_capacitance_as_reactance() -> None:
    freq = np.array([100.0, 1000.0])
    shunt = fixture_admittance(freq, None, 5.3e-11)
    assert np.allclose(shunt.y.real, 0.0)
    assert shunt.y.imag == pytest.approx(2 * math.pi * freq * 5.3e-11)


def test_fixture_admittance_reports_points_beyond_the_measured_band() -> None:
    """Blocker 4. Holding the endpoint is a decision, so it is counted and logged."""
    table = _dielectric_table()
    freq = np.logspace(math.log10(1.2), math.log10(2.0e5), 40)   # starts below 14.28 Hz
    held = fixture_admittance(freq, table, 0.0, beyond_coverage="hold")
    assert held.n_held > 0
    assert held.coverage_hz[0] == pytest.approx(14.28, rel=1e-3)
    below = freq < held.coverage_hz[0]
    assert np.allclose(held.y.real[below], table.G_S[0])
    assert 0.0 < held.held_fraction < 1.0


def test_fixture_admittance_drop_policy_emits_nan_for_uncovered_points() -> None:
    table = _dielectric_table()
    freq = np.logspace(math.log10(1.2), math.log10(2.0e5), 40)
    dropped = fixture_admittance(freq, table, 0.0, beyond_coverage="drop")
    below = freq < dropped.coverage_hz[0]
    assert np.all(np.isnan(dropped.y.real[below]))
    assert np.all(np.isfinite(dropped.y.real[~below]))
    assert dropped.n_held == int(np.count_nonzero(below))


def test_fixture_admittance_rejects_an_unknown_policy() -> None:
    with pytest.raises(ValueError, match="beyond_coverage"):
        fixture_admittance(np.array([100.0]), _dielectric_table(), 0.0,
                           beyond_coverage="wing it")


def test_known_shunt_is_recovered_through_the_fit_not_absorbed() -> None:
    """A spectrum built *with* a fixture shunt is only recovered when it is supplied.

    The positive control that the shunt reaches the model: fitting the same spectrum
    with the shunt zeroed gives a materially different ``R_sol``.
    """
    table = _dielectric_table()
    specs, blind = [], []
    for label, r_sol in TRUE_R_SOL.items():
        freq = np.logspace(math.log10(14.28), math.log10(2.0e5), 40)
        y = fixture_admittance(freq, table, 5.3e-11).y
        params = {**TRUE_SHARED, "R0": 0.15 * r_sol, "R1": 0.85 * r_sol, "Qd": 2e-6}
        z = model_impedance(freq, params, y, 0.0)
        specs.append(ConstrainedSpectrum(label, freq, z, y, reference_ohm=r_sol))
        blind.append(ConstrainedSpectrum(label, freq, z, np.zeros(40, dtype=complex),
                                         reference_ohm=r_sol))

    supplied = fit_shared(specs)
    for spec in specs:
        assert fit_frozen(spec, supplied).R_sol == pytest.approx(
            spec.reference_ohm, rel=1e-3), spec.label

    ignored = fit_shared(blind)
    worst = max(abs(fit_frozen(s, ignored).R_sol / s.reference_ohm - 1.0)
                for s in blind)
    assert worst > 0.01, "zeroing the shunt changed nothing — it is not reaching the model"


