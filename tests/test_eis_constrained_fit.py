# ── Blocker 1: the tolerance is load-bearing ─────────────────────────────────

def test_constrained_fit_tol_is_far_tighter_than_the_scipy_default() -> None:
    assert CONSTRAINED_FIT_TOL <= 1e-12


def test_loose_tolerance_stops_short_of_the_minimum() -> None:
    """The stacked fit at scipy's default terminates *reporting success*.

    Measured on the real NIST set the gap is 8014 % against 1.56 %. Synthetically the
    gap is smaller — noise-free data is kind — so the assertion is on the cost the
    optimiser reached, which is the quantity that is actually wrong, and on the fact
    that the loose run still reports a successful status.
    """
    ladder = [synth(k, v) for k, v in TRUE_R_SOL.items()]
    loose = fit_shared(ladder, tol=1e-8)
    tight = fit_shared(ladder, tol=CONSTRAINED_FIT_TOL)
    assert tight.cost < loose.cost
    assert loose.status > 0, "the loose run reports success — that is the whole problem"
    assert tight.tol == CONSTRAINED_FIT_TOL and loose.tol == 1e-8


def test_loose_tolerance_is_warned_about(monkeypatch) -> None:
    """Asserted on the logger call, not on log capture — structlog routing varies."""
    from softae.analysis.eis import constrained_fit as module

    events: list[tuple[str, dict]] = []
    monkeypatch.setattr(
        module.logger, "warning",
        lambda event, **kw: events.append((event, kw)))
    fit_shared([synth(k, v) for k, v in TRUE_R_SOL.items()], tol=1e-6)
    assert [e for e, _ in events] == ["eis_constrained_fit_loose_tolerance"]
    assert events[0][1]["tol"] == 1e-6


def test_tight_tolerance_is_not_warned_about(monkeypatch) -> None:
    """The negative half. Without it the test above cannot distinguish a warning that
    fires on the loose case from one that fires unconditionally."""
    from softae.analysis.eis import constrained_fit as module

    events: list[str] = []
    monkeypatch.setattr(module.logger, "warning",
                        lambda event, **kw: events.append(event))
    fit_shared([synth(k, v) for k, v in TRUE_R_SOL.items()])
    assert events == []


def test_tolerance_reaches_the_optimiser(monkeypatch) -> None:
    """Positive control: the keyword must actually arrive at ``least_squares``.

    Without this the test above could pass on two runs that both used the default —
    SUBAGENT_RULES §3.1(e).
    """
    from softae.analysis.eis import constrained_fit as module

    seen: list[float] = []
    real = module.least_squares

    def spy(*args, **kwargs):
        seen.append(kwargs.get("ftol"))
        return real(*args, **kwargs)

    monkeypatch.setattr(module, "least_squares", spy)
    fit_shared([synth(k, v) for k, v in TRUE_R_SOL.items()], tol=1e-9)
    assert seen and set(seen) == {1e-9}


